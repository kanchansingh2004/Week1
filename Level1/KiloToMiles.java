// Creating Kilo_To_Miles Class to convert the value from kilometer to miles.

 class KiloToMiles{
	 
	public static void main(String args[])
	{
		// Create a variable to initialize the value in kilometer .
		float distanceInKm=10.8f;
		
		// Create a variable to convert the distance in km to miles.
		float distanceInMiles=distanceInKm*1.6f;
		
		
		// Printing the average marks of Sam
		System.out.println(" The distance "+ distanceInKm + "km in miles is " + distanceInMiles);
		
	}
}